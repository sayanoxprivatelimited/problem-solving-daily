/**
 * Page wiring: load the generated catalogue data, render the DOM, boot the scenes.
 *
 * Design rule: the DOM is the source of truth for content (it works without
 * WebGL), and the scenes are an enhancement. Each scene boots inside its own
 * try/catch, so one broken canvas never takes the page down.
 */
import catalog from '../data/catalog.js';
import {
  categoryColor,
  colorToCss,
  filterProblems,
  formatNumber,
  matchesQuery,
  prettyCategory,
  stepIndex,
  summarize,
} from './layout.js';

/**
 * Every scene is imported lazily, on purpose.
 *
 * A scene pulls in Three.js, which is a ~1 MB module. If that request fails — an
 * offline visitor, a blocked CDN, a browser with the feature switched off — a
 * static import would take the whole entry point down with it and the page would
 * render nothing. A dynamic import fails inside its own try/catch instead, so the
 * catalogue below stays readable and only the canvases fall back to a note.
 */
const sceneModules = {
  hero: () => import('./scenes/hero.js'),
  galaxy: () => import('./scenes/galaxy.js'),
  bars: () => import('./scenes/bars.js'),
  structure: () => import('./scenes/structure.js'),
};

const THEME_KEY = 'psd-theme';

/** The origin the canonical link names; every share URL is built from it. */
const CANONICAL_URL = document.querySelector('link[rel="canonical"]')?.href
  || `${window.location.origin}${window.location.pathname}`;

const state = {
  problems: [],
  category: 'all',
  query: '',
  selected: null,
  galaxy: null,
  theme: 'dark',
};

const tooltip = document.getElementById('tooltip');
const sheet = document.getElementById('detail');

/* ------------------------------------------------------------------ data -- */
/**
 * The catalogue is imported, not fetched.
 *
 * `site/data/catalog.js` is generated by `scripts/build_catalog.py`, so the data
 * ships with the module graph: no request to fail, no loading state, and the page
 * also renders when it is opened from disk instead of a server.
 */
function loadData() {
  if (!catalog || !Array.isArray(catalog.problems) || !catalog.problems.length) {
    throw new Error('site/data/catalog.js is empty — run: python scripts/build_catalog.py');
  }
  return catalog;
}

function showDataError(error) {
  document.body.classList.add('no-webgl');
  const cards = document.getElementById('cards');
  cards.innerHTML = `
    <div class="card">
      <h3 class="card__title">The catalogue data is missing</h3>
      <p class="card__concepts">
        Run <code>python scripts/build_catalog.py</code> to generate
        <code>site/data/catalog.js</code>, then serve the folder:
        <code>python3 -m http.server --directory site</code>.
      </p>
      <p class="card__concepts">(${error.message})</p>
    </div>`;
  const footer = document.getElementById('footer-meta');
  if (footer) footer.textContent = 'data unavailable — see the message above';
}

/* ------------------------------------------------------------------- DOM -- */
function hydrateLinks(data) {
  const repo = data.repository?.url ?? '#';
  for (const id of ['repo-link', 'hero-repo']) {
    const element = document.getElementById(id);
    if (element) element.href = repo;
  }
}

function renderHeroStats(data) {
  const stats = summarize(state.problems);
  const items = [
    [formatNumber(stats.problems), 'problems'],
    [formatNumber(stats.tests), 'tests'],
    [formatNumber(stats.doctests), 'doctests'],
    [formatNumber(stats.categories), 'categories'],
  ];

  const container = document.getElementById('hero-stats');
  container.innerHTML = items
    .map(
      ([value, label]) => `
      <div class="stat">
        <span class="stat__value">${value}</span>
        <span class="stat__label">${label}</span>
      </div>`,
    )
    .join('');
}

function renderLegend(categories) {
  const legend = document.getElementById('hero-legend');
  legend.innerHTML = categories
    .map(
      (category) => `
      <li style="--cat: ${colorToCss(categoryColor(category.name))}">
        <span class="legend__swatch" aria-hidden="true"></span>
        ${prettyCategory(category.name)} · ${category.problems}
      </li>`,
    )
    .join('');
}

function renderFilters(categories) {
  const container = document.getElementById('filters');
  const options = [{ name: 'all', label: 'All', count: state.problems.length }].concat(
    categories.map((category) => ({
      name: category.name,
      label: prettyCategory(category.name),
      count: category.problems,
    })),
  );

  container.innerHTML = options
    .map(
      (option) => `
      <button class="filter" type="button" data-category="${option.name}"
        aria-pressed="${option.name === state.category}"
        style="--cat: ${colorToCss(categoryColor(option.name))}">
        ${option.label} <span aria-hidden="true">${option.count}</span>
      </button>`,
    )
    .join('');

  container.addEventListener('click', (event) => {
    const button = event.target.closest('button[data-category]');
    if (!button) return;
    setCategory(button.dataset.category);
  });
}

function visibleProblems() {
  return filterProblems(state.problems, state.category).filter((problem) =>
    matchesQuery(problem, state.query),
  );
}

function updateCount(visible) {
  const counter = document.getElementById('result-count');
  if (!counter) return;
  const total = state.problems.length;
  const scope = state.query ? ` matching “${state.query}”` : '';
  counter.textContent =
    visible.length === total
      ? `${total} problems${scope}`
      : `${visible.length} of ${total} problems${scope}`;
}

function cardMarkup(problem) {
  const color = colorToCss(categoryColor(problem.category));
  return `
        <article class="card" id="problem-${problem.slug}" style="--cat: ${color}"
          data-index="${problem.index}" data-slug="${problem.slug}">
          <header class="card__head">
            <span class="card__index">${String(problem.index).padStart(2, '0')}</span>
            <span class="badge">${prettyCategory(problem.category)}</span>
            <span class="badge badge--level" data-level="${problem.level}">${problem.level}</span>
          </header>
          <h3 class="card__title">
            <a href="${problem.brief_url}" target="_blank" rel="noreferrer">${problem.title}</a>
          </h3>
          <p class="card__summary">${problem.summary ?? ''}</p>
          <p class="card__concepts">${problem.concepts.join(' · ')}</p>
          <footer class="card__foot">
            <span>${problem.tests} tests</span>
            <span>${problem.doctests} doctests</span>
            <button class="card__more" type="button" data-detail="${problem.index}">Details</button>
            <a href="${problem.code_url}" target="_blank" rel="noreferrer">code ↗</a>
          </footer>
        </article>`;
}

function renderCards() {
  const container = document.getElementById('cards');
  const visible = visibleProblems();
  updateCount(visible);

  if (!visible.length) {
    container.innerHTML = `
      <div class="card card--empty">
        <h3 class="card__title">Nothing matches that</h3>
        <p class="card__concepts">
          Try a concept like <code>regex</code>, a level like <code>hard</code>, or
          <button class="link-button" type="button" data-clear>clear the filters</button>.
        </p>
      </div>`;
    return;
  }

  container.innerHTML = visible.map(cardMarkup).join('');

  for (const card of container.querySelectorAll('.card[data-index]')) {
    const index = Number(card.dataset.index);
    card.addEventListener('pointerenter', () => state.galaxy?.focus(index));
    card.addEventListener('pointerleave', () => state.galaxy?.focus(null));
  }

  if (state.selected) paintSelection(state.selected);
}

function renderNumbers(data) {
  const stats = summarize(state.problems);
  const stack = document.getElementById('stat-stack');
  const levelRows = ['hard', 'medium', 'easy']
    .map((level) => {
      const count = stats.levels[level] ?? 0;
      const share = stats.problems ? Math.round((count / stats.problems) * 100) : 0;
      return `
        <div class="level-row">
          <span>${level}</span>
          <span class="level-bar"><span style="width: ${share}%"></span></span>
          <span>${count}</span>
        </div>`;
    })
    .join('');

  stack.innerHTML = `
    <div class="stat-card">
      <div class="stat-card__value">${formatNumber(stats.tests)}</div>
      <div class="stat-card__label">tests, all green</div>
    </div>
    <div class="stat-card">
      <div class="stat-card__value">${formatNumber(stats.doctests)}</div>
      <div class="stat-card__label">doctest examples executed</div>
    </div>
    <div class="stat-card">
      <div class="stat-card__value">${formatNumber(stats.solutionLines)}</div>
      <div class="stat-card__label">lines of solution code</div>
    </div>
    <div class="stat-card">
      <div class="stat-card__value">${stats.categories}</div>
      <div class="stat-card__label">categories</div>
      <div class="levels">${levelRows}</div>
    </div>`;

  const footer = document.getElementById('footer-meta');
  if (footer) {
    footer.textContent = `${stats.problems} problems · ${formatNumber(stats.tests)} tests · generated from problem.md front matter`;
  }
}

/* -------------------------------------------------------------- selection -- */
function paintSelection(index) {
  for (const card of document.querySelectorAll('.card[data-index]')) {
    card.classList.toggle('is-active', Number(card.dataset.index) === index);
  }
}

function selectProblem(problem) {
  state.selected = problem.index;
  replaceUrl({ query: state.query, slug: problem.slug });
  paintSelection(problem.index);
  state.galaxy?.focus(problem.index);
  const card = document.querySelector(`.card[data-index="${problem.index}"]`);
  if (card) {
    card.classList.add('is-active');
    card.scrollIntoView({ block: 'nearest', behavior: 'smooth' });
  }
}

function setCategory(category) {
  state.category = category;
  for (const button of document.querySelectorAll('button[data-category]')) {
    button.setAttribute('aria-pressed', String(button.dataset.category === category));
  }
  renderCards();
  state.galaxy?.setFilter(category);
}

/* ---------------------------------------------------------------- sheet -- */
function openDetail(index) {
  const problem = state.problems.find((entry) => entry.index === index);
  if (!problem) return;

  const category = document.getElementById('detail-category');
  const title = document.getElementById('detail-title');
  const meta = document.getElementById('detail-meta');
  const summary = document.getElementById('detail-summary');
  const rules = document.getElementById('detail-criteria');
  const links = document.getElementById('detail-links');

  if (category) category.textContent = prettyCategory(problem.category);
  if (title) title.textContent = problem.title;
  if (meta) {
    meta.textContent =
      `${problem.level} · ${problem.tests} tests · ${problem.doctests} doctests`
      + ` · ${problem.solution_lines} lines of solution`;
  }
  if (summary) summary.textContent = problem.summary ?? '';

  // Built as nodes, not innerHTML: the rules come from markdown and may contain
  // characters that would otherwise be read as markup.
  if (rules) {
    rules.replaceChildren(
      ...(problem.criteria ?? []).map((rule) => {
        const item = document.createElement('li');
        item.textContent = rule;
        return item;
      }),
    );
  }

  if (links) {
    links.replaceChildren(
      ...[
        ['Read the brief ↗', problem.brief_url],
        ['Solution ↗', problem.code_url],
      ].map(([label, href]) => {
        const link = document.createElement('a');
        link.href = href;
        link.target = '_blank';
        link.rel = 'noreferrer';
        link.textContent = label;
        return link;
      }),
    );
  }

  state.selected = problem.index;
  paintSelection(problem.index);
  state.galaxy?.focus(problem.index);

  const share = document.getElementById('detail-share');
  if (share) {
    const url = urlFor({ slug: problem.slug });
    share.href = shareTargets({
      url,
      text: `Sayanox Problem Solve Daily — ${problem.title}`,
      title: problem.title,
    }).x;
  }
  replaceUrl({ query: state.query, slug: problem.slug });

  if (sheet && typeof sheet.showModal === 'function') {
    if (!sheet.open) sheet.showModal();
  } else if (sheet) {
    sheet.setAttribute('open', '');
  }
}

function closeDetail() {
  if (!sheet) return;
  if (typeof sheet.close === 'function' && sheet.open) sheet.close();
  else sheet.removeAttribute('open');
}

/* ---------------------------------------------------------------- theme -- */
function applyTheme(theme) {
  state.theme = theme === 'light' ? 'light' : 'dark';
  document.documentElement.dataset.theme = state.theme;

  const button = document.getElementById('theme-toggle');
  if (!button) return;
  const light = state.theme === 'light';
  button.textContent = light ? '☾' : '☀';
  button.setAttribute('aria-pressed', String(light));
  button.setAttribute('aria-label', light ? 'Switch to dark theme' : 'Switch to light theme');
}

function initTheme() {
  let stored = null;
  try {
    stored = localStorage.getItem(THEME_KEY);
  } catch (error) {
    stored = null; // storage can be blocked; the OS preference still applies
  }
  const prefersLight = window.matchMedia?.('(prefers-color-scheme: light)').matches ?? false;
  applyTheme(stored ?? (prefersLight ? 'light' : 'dark'));

  document.getElementById('theme-toggle')?.addEventListener('click', () => {
    const next = state.theme === 'light' ? 'dark' : 'light';
    applyTheme(next);
    try {
      localStorage.setItem(THEME_KEY, next);
    } catch (error) {
      /* nothing to save, the choice still holds for this visit */
    }
  });
}

/* --------------------------------------------------------------- tooltip -- */
function showTooltip(problem, point) {
  if (!problem || !point) {
    tooltip.hidden = true;
    return;
  }
  tooltip.innerHTML = `<strong>${problem.title}</strong>
    <span>${prettyCategory(problem.category)} · ${problem.level} · ${problem.tests} tests</span>`;
  tooltip.hidden = false;
  tooltip.style.left = `${point.x}px`;
  tooltip.style.top = `${point.y}px`;
}

function hideTooltip() {
  tooltip.hidden = true;
}

function tooltipHandlers() {
  return {
    onHover: (problem, point) => (problem ? showTooltip(problem, point) : hideTooltip()),
  };
}

/* ---------------------------------------------------------------- scenes -- */
async function bootScene(name, factory) {
  try {
    return await factory();
  } catch (error) {
    console.warn(`[${name}] scene unavailable:`, error);
    document.body.classList.add('no-webgl');
    return null;
  }
}

/**
 * Boot a scene the first time its canvas comes close to the viewport.
 *
 * Four live WebGL contexts on first paint is the difference between a page that
 * settles instantly and one that stutters on a mid-range phone, and three of these
 * scenes are nowhere near the fold. The observer fires a little early (400px) so
 * the module is already downloaded by the time the canvas is actually visible.
 */
function bootWhenVisible(name, canvas, start) {
  if (!canvas) return;

  // Read the constructor off `window`: a bare `IntersectionObserver` is a
  // ReferenceError anywhere the API is missing, and this page must survive that.
  const Observer = window.IntersectionObserver;
  if (typeof Observer !== 'function') {
    void bootScene(name, start);
    return;
  }

  const observer = new Observer(
    (entries) => {
      if (!entries.some((entry) => entry.isIntersecting)) return;
      observer.disconnect();
      void bootScene(name, start);
    },
    { rootMargin: '400px 0px' },
  );
  observer.observe(canvas);
}

function startScenes() {
  bootWhenVisible('hero', document.getElementById('hero-canvas'), async () => {
    const { createHeroScene } = await sceneModules.hero();
    return createHeroScene(document.getElementById('hero-canvas'), state.problems);
  });

  bootWhenVisible('galaxy', document.getElementById('galaxy-canvas'), async () => {
    const { createGalaxyScene } = await sceneModules.galaxy();
    state.galaxy = createGalaxyScene(document.getElementById('galaxy-canvas'), state.problems, {
      ...tooltipHandlers(),
      onSelect: selectProblem,
      // A filter or a selection may already exist by the time this loads.
      initialFilter: state.category,
    });
    if (state.selected !== null) state.galaxy.focus(state.selected);
    return state.galaxy;
  });

  bootWhenVisible('bars', document.getElementById('bars-canvas'), async () => {
    const { createBarsScene } = await sceneModules.bars();
    return createBarsScene(
      document.getElementById('bars-canvas'),
      state.problems,
      tooltipHandlers(),
    );
  });

  bootWhenVisible('structure', document.getElementById('structure-canvas'), async () => {
    const { createStructureScene } = await sceneModules.structure();
    return createStructureScene(document.getElementById('structure-canvas'), {
      labels: ['problem.md', 'solution/', 'tests/'],
    });
  });
}

function clearFilters() {
  state.query = '';
  const input = document.getElementById('search');
  if (input) input.value = '';
  setCategory('all');
  syncUrl(); // the ?q= that the empty state was reached through must go too
}

/** Move the selection through the cards currently on screen, wrapping at both ends. */
function moveSelection(direction) {
  const buttons = [...document.querySelectorAll('.card[data-index] .card__more')];
  if (!buttons.length) return;

  const current = buttons.findIndex(
    (button) => Number(button.closest('.card').dataset.index) === state.selected,
  );
  const next = stepIndex(buttons.length, current, direction);
  const target = buttons[next];
  if (!target) return;

  const index = Number(target.closest('.card').dataset.index);
  state.selected = index;
  paintSelection(index);
  state.galaxy?.focus(index);
  target.focus();
}

/* ------------------------------------------------------------ deep links -- */
/**
 * The page state lives in the URL, so a share link opens the same view.
 *
 *   ?q=tokenizer      the search box, pre-filled
 *   ?p=01-bpe-tokenizer   the detail sheet, open on that problem
 *   #problem-<slug>   the card itself (an anchor, no script needed)
 *
 * `replaceState`, not `pushState`: typing in the search box must not fill the
 * back button with one entry per keystroke.
 */
function urlFor({ query = '', slug = '' }) {
  const url = new URL(window.location.href);
  url.hash = '';
  url.search = '';
  if (query) url.searchParams.set('q', query);
  if (slug) url.searchParams.set('p', slug);
  return url.toString();
}

function replaceUrl(params) {
  const next = urlFor(params);
  if (next === window.location.href) return;
  try {
    window.history.replaceState(null, '', next);
  } catch (error) {
    /* file:// and sandboxed frames refuse this; the page still works */
  }
}

function slugOf(index) {
  return state.problems.find((problem) => problem.index === index)?.slug ?? '';
}

/** Write the current search + selection back into the address bar. */
function syncUrl() {
  replaceUrl({ query: state.query, slug: slugOf(state.selected) });
}

function applyDeepLink() {
  const params = new URLSearchParams(window.location.search);
  const query = (params.get('q') ?? '').trim();
  if (query) {
    state.query = query;
    const input = document.getElementById('search');
    if (input) input.value = query;
    renderCards();
  }

  const hash = window.location.hash.startsWith('#problem-')
    ? window.location.hash.slice('#problem-'.length)
    : '';
  const wanted = params.get('p') || hash;
  if (!wanted) return;

  const problem = state.problems.find(
    (entry) => entry.slug === wanted || String(entry.index) === wanted,
  );
  if (!problem) return;

  selectProblem(problem);
  openDetail(problem.index);
}

/* ---------------------------------------------------------------- share -- */
function shareSummary() {
  const count = state.problems.length || 12;
  return `Sayanox Problem Solve Daily — ${count} hard engineering problems, each with a brief, runnable Python and a test suite`;
}

function shareTargets({ url, text, title }) {
  const link = encodeURIComponent(url);
  const say = encodeURIComponent(`${text} ${url}`);
  return {
    x: `https://twitter.com/intent/tweet?url=${link}&text=${encodeURIComponent(text)}`,
    linkedin: `https://www.linkedin.com/sharing/share-offsite/?url=${link}`,
    whatsapp: `https://wa.me/?text=${say}`,
    telegram: `https://t.me/share/url?url=${link}&text=${encodeURIComponent(text)}`,
    reddit: `https://www.reddit.com/submit?url=${link}&title=${encodeURIComponent(title)}`,
  };
}

async function copyText(text) {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch (error) {
    /* permission denied: fall through to the selection trick */
  }
  try {
    const area = document.createElement('textarea');
    area.value = text;
    area.setAttribute('readonly', '');
    area.style.position = 'fixed';
    area.style.top = '-1000px';
    document.body.append(area);
    area.select();
    const copied = typeof document.execCommand === 'function' && document.execCommand('copy');
    area.remove();
    return Boolean(copied);
  } catch (error) {
    return false;
  }
}

function initShare() {
  const note = document.getElementById('share-note');
  const announce = (message) => {
    if (note) note.textContent = message;
  };

  // The markup ships with static targets that already point at the live site;
  // rewriting them here keeps previews and local runs on the right URL.
  const targets = shareTargets({
    url: CANONICAL_URL,
    text: shareSummary(),
    title: document.title,
  });
  for (const link of document.querySelectorAll('[data-share-net]')) {
    const href = targets[link.dataset.shareNet];
    if (href) link.href = href;
  }

  document.getElementById('copy-link')?.addEventListener('click', async () => {
    const copied = await copyText(window.location.href);
    announce(copied ? 'Link copied — paste it anywhere.' : 'Copy failed — select the address bar instead.');
    replaceUrl({ query: state.query, slug: slugOf(state.selected) });
  });

  document.getElementById('hero-share')?.addEventListener('click', async () => {
    const payload = {
      title: document.title,
      text: shareSummary(),
      url: window.location.href,
    };
    if (navigator.share) {
      try {
        await navigator.share(payload);
        return;
      } catch (error) {
        /* the visitor closed the native sheet: fall through to a copy */
      }
    }
    const copied = await copyText(payload.url);
    announce(copied ? 'Link copied — paste it anywhere.' : 'Copy failed — select the address bar instead.');
  });

  document.getElementById('detail-copy')?.addEventListener('click', async () => {
    const detailNote = document.getElementById('detail-note');
    const copied = await copyText(urlFor({ slug: slugOf(state.selected) }));
    if (detailNote) {
      detailNote.textContent = copied ? 'Link copied' : 'Copy failed';
    }
  });
}

/* ------------------------------------------------------------------ init -- */
async function bootstrap() {
  try {
    const data = loadData();
    state.problems = data.problems;

    hydrateLinks(data);
    renderHeroStats(data);
    renderLegend(data.categories);
    renderFilters(data.categories);
    renderCards();
    renderNumbers(data);
    initTheme();

    const search = document.getElementById('search');
    search?.addEventListener('input', () => {
      state.query = search.value.trim();
      renderCards();
      syncUrl();
    });

    initShare();
    applyDeepLink();

    document.getElementById('detail-close')?.addEventListener('click', closeDetail);
    sheet?.addEventListener('click', (event) => {
      if (event.target === sheet) closeDetail(); // clicking the backdrop closes it
    });

    document.getElementById('cards')?.addEventListener('click', (event) => {
      if (!(event.target instanceof Element)) return;
      const details = event.target.closest('button[data-detail]');
      if (details) openDetail(Number(details.dataset.detail));
      else if (event.target.closest('[data-clear]')) clearFilters();
    });

    // Not awaited: each canvas boots itself once it approaches the viewport.
    startScenes();

    // Keyboard users walk the visible cards without touching the mouse.
    window.addEventListener('keydown', (event) => {
      const target = event.target instanceof Element ? event.target : null;
      if (target?.closest('input, textarea, select')) return;

      if (event.key === 'Escape') {
        state.selected = null;
        paintSelection(null);
        state.galaxy?.focus(null);
        hideTooltip();
        closeDetail();
        return;
      }
      if (event.key === 'ArrowDown' || event.key === 'j') {
        event.preventDefault();
        moveSelection(1);
      }
      if (event.key === 'ArrowUp' || event.key === 'k') {
        event.preventDefault();
        moveSelection(-1);
      }
    });
  } catch (error) {
    console.error(error);
    showDataError(error);
  }
}

bootstrap();
