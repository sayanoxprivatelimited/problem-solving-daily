#!/usr/bin/env python3
"""Generate the crawl-facing files for the 3D site.

Search engines and link previews do not run the page's JavaScript (or they run it
grudgingly, late, and never twice), so everything that has to be *found* is written
as static markup or as a static file:

    site/robots.txt          crawl policy + the sitemap location
    site/sitemap.xml         the one canonical URL this site answers on
    site/index.html          a generated JSON-LD block (inside the seo:jsonld markers)

The JSON-LD graph is generated from ``site/data/problems.json`` — the same file the
page renders — so the structured data can never advertise a problem that has been
deleted, a test count that is wrong, or a deep link that does not resolve.

    python scripts/build_seo.py           # rewrite robots.txt, sitemap.xml, JSON-LD
    python scripts/build_seo.py --check   # exit 1 if any of them is stale

Like the catalogue, the outputs are artifacts of the briefs, not source: edit
``problem.md`` and re-run this script.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
DATA = SITE / "data" / "problems.json"
INDEX = SITE / "index.html"
ROBOTS = SITE / "robots.txt"
SITEMAP = SITE / "sitemap.xml"

#: The canonical origin. Every absolute URL in the structured data hangs off it,
#: so changing the domain is a one-line change here plus a re-run.
SITE_URL = "https://problem-solving-daily.vercel.app"
SITE_HOST = SITE_URL.split("://", 1)[1]

BRAND = "Sayanox Problem Solve Daily"
BRAND_SHORT = "Sayanox PSD"
ORGANIZATION = "Sayanox Private Limited"
ORGANIZATION_URL = "https://github.com/sayanoxprivatelimited"
REPOSITORY_URL = "https://github.com/sayanoxprivatelimited/problem-solving-daily"

MARKER_START = "    <!-- seo:jsonld:start — generated by scripts/build_seo.py, do not edit by hand -->"
MARKER_END = "    <!-- seo:jsonld:end -->"

#: Mirrors CATEGORY_LABELS in site/js/layout.js; a site test asserts they agree.
CATEGORY_LABELS = {
    "ai": "AI",
    "backend": "Backend",
    "cli": "CLI",
    "coding": "Coding",
    "data": "Data",
    "network": "Network",
}

#: Structured-data descriptions are not truncated by Google the way meta
#: descriptions are, so this one is allowed to finish its sentence.
DESCRIPTION_LIMIT = 300
CARD_LIMIT = 200


# --------------------------------------------------------------- helpers -- #
def collapse(text: str) -> str:
    """Flatten markdown prose into a single line of plain text."""
    text = re.sub(r"[*_`]+", "", text or "")
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    return re.sub(r"\s+", " ", text).strip()


def trim(text: str, limit: int) -> str:
    """Cut on a word boundary and keep the sentence looking finished."""
    if len(text) <= limit:
        return text
    cut = text[: limit - 1].rsplit(" ", 1)[0]
    return cut.rstrip(",;:—-") + "…"


def category_label(name: str) -> str:
    return CATEGORY_LABELS.get(name, str(name).capitalize())


def trim_sentence(text: str, limit: int) -> str:
    """Cut on the last full sentence that fits, so search results read cleanly."""
    if len(text) <= limit:
        return text
    head = text[:limit]
    stop = max(head.rfind(". "), head.rfind("! "), head.rfind("? "))
    if stop >= limit // 2:
        return head[: stop + 1]
    return trim(text, limit)


def problem_url(slug: str) -> str:
    """The shareable deep link for one problem (the page reads ``?p=``)."""
    return f"{SITE_URL}/?p={slug}"


def site_description(data: dict) -> str:
    stats = data["stats"]
    text = (
        f"{BRAND}: {stats['problems']} hard engineering problems — tokenizers, leases "
        f"with fencing tokens, circuit breakers — each with a brief, runnable Python, "
        f"{stats['tests']} tests and a CLI, browsable in 3D."
    )
    return trim(text, DESCRIPTION_LIMIT)


# ------------------------------------------------------------ structured -- #
def build_graph(data: dict) -> dict:
    """A schema.org graph describing the site, its owner and the catalogue."""
    stats = data["stats"]
    categories = ", ".join(category_label(category["name"]) for category in data["categories"])
    description = site_description(data)

    website = {
        "@type": "WebSite",
        "@id": f"{SITE_URL}/#website",
        "url": f"{SITE_URL}/",
        "name": BRAND,
        "alternateName": [BRAND_SHORT, "Problem Solve Daily", "Sayanox"],
        "description": description,
        "inLanguage": "en",
        "publisher": {"@id": f"{SITE_URL}/#organization"},
        "potentialAction": {
            "@type": "SearchAction",
            "target": {
                "@type": "EntryPoint",
                "urlTemplate": f"{SITE_URL}/?q={{search_term_string}}",
            },
            "query-input": "required name=search_term_string",
        },
    }

    organization = {
        "@type": "Organization",
        "@id": f"{SITE_URL}/#organization",
        "name": ORGANIZATION,
        "alternateName": "Sayanox",
        "url": ORGANIZATION_URL,
        "sameAs": [ORGANIZATION_URL, REPOSITORY_URL],
        "description": (
            "Sayanox builds and ships software. Sayanox Problem Solve Daily is its "
            "public practice log: real engineering problems solved end to end."
        ),
    }

    items = []
    for problem in data["problems"]:
        name = problem["title"]
        summary = trim_sentence(collapse(problem.get("summary", "")), CARD_LIMIT)
        items.append(
            {
                "@type": "ListItem",
                "position": problem["index"],
                "url": problem_url(problem["slug"]),
                "item": {
                    "@type": "LearningResource",
                    "@id": f"{SITE_URL}/?p={problem['slug']}#problem",
                    "name": name,
                    "headline": name,
                    "description": summary,
                    "url": problem_url(problem["slug"]),
                    "learningResourceType": "coding challenge",
                    "educationalLevel": problem["level"],
                    "educationalUse": "practice",
                    "isAccessibleForFree": True,
                    "inLanguage": "en",
                    "license": "https://github.com/sayanoxprivatelimited/"
                    "problem-solving-daily/blob/main/LICENSE",
                    "teaches": problem["concepts"],
                    "keywords": ", ".join(problem["concepts"]),
                    "about": problem["category"],
                    "author": {"@id": f"{SITE_URL}/#organization"},
                    "isPartOf": {"@id": f"{SITE_URL}/#collection"},
                    "sameAs": problem["brief_url"],
                    "comment": (
                        f"{problem['tests']} tests, {problem['doctests']} doctests, "
                        f"{problem['solution_lines']} lines of solution"
                    ),
                },
            }
        )

    item_list = {
        "@type": "ItemList",
        "@id": f"{SITE_URL}/#catalogue",
        "name": f"{BRAND} — {stats['problems']} engineering problems",
        "description": (
            f"{stats['problems']} problems across {stats['categories']} categories, "
            f"backed by {stats['tests']} tests and {stats['doctests']} doctests."
        ),
        "numberOfItems": stats["problems"],
        "itemListOrder": "https://schema.org/ItemListOrderAscending",
        "itemListElement": items,
    }

    collection = {
        "@type": "CollectionPage",
        "@id": f"{SITE_URL}/#collection",
        "url": f"{SITE_URL}/",
        "name": f"{BRAND} — the catalogue",
        "description": (
            f"A browsable 3D catalogue of {stats['problems']} engineering problems in "
            f"{categories}. Every entry ships a written brief, runnable Python, a test "
            "suite and a CLI."
        ),
        "isPartOf": {"@id": f"{SITE_URL}/#website"},
        "about": [category["name"] for category in data["categories"]],
        "mainEntity": {"@id": f"{SITE_URL}/#catalogue"},
        "inLanguage": "en",
        "license": REPOSITORY_URL + "/blob/main/LICENSE",
    }

    return {"@context": "https://schema.org", "@graph": [website, organization, collection, item_list]}


def render_jsonld(data: dict) -> str:
    graph = build_graph(data)
    payload = json.dumps(graph, indent=2, ensure_ascii=True)
    payload = payload.replace("</", "<\\/")  # never let the payload close its own tag
    return (
        f'{MARKER_START}\n'
        f'    <script type="application/ld+json">\n{payload}\n    </script>\n'
        f"{MARKER_END}"
    )


# --------------------------------------------------------------- outputs -- #
def render_robots(data: dict) -> str:
    return (
        f"# {BRAND} — a 3D catalogue of real engineering problems.\n"
        f"# {REPOSITORY_URL}\n"
        "User-agent: *\n"
        "Allow: /\n"
        "\n"
        f"Sitemap: {SITE_URL}/sitemap.xml\n"
        f"Host: {SITE_HOST}\n"
    )


def render_sitemap(data: dict) -> str:
    """One entry: the site is a single page, and ?p= links canonicalise to it."""
    stats = data["stats"]
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f"<!-- {BRAND} — generated by scripts/build_seo.py -->\n"
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        "  <url>\n"
        f"    <loc>{SITE_URL}/</loc>\n"
        "    <changefreq>weekly</changefreq>\n"
        "    <priority>1.0</priority>\n"
        "  </url>\n"
        f"  <!-- {stats['problems']} problems are shareable as {SITE_URL}/?p=<slug> -->\n"
        "</urlset>\n"
    )


#: Count-bearing phrases that live *outside* the generated JSON-LD block: the
#: <title>, the meta descriptions, the visible headline, the snippet in the "how to
#: run" card and the percent-encoded share targets. Keeping them here means a new
#: problem can never leave the page advertising last week's test count.
COUNT_PATTERNS = (
    (r"\b\d+(?= hard engineering problems)", "problems"),
    (r"\b\d+(?= hard problems)", "problems"),
    (r"\b\d+(?= engineering problems)", "problems"),
    (r"\b\d+(?= problems, )", "problems"),
    (r"\b\d+(?= problems across )", "problems"),
    (r"(?<= problems, )\d+", "categories"),
    (r"(?<= across )\d+(?= categories)", "categories"),
    (r"\b\d+(?= tests\b)", "tests"),
    (r"\b\d+(?= doctests\b)", "doctests"),
    # Percent-encoded share targets: no \b here, "%20" and the digits are all
    # word characters, so a boundary never exists between them. The lookbehind
    # anchors on the encoded space, otherwise "%2012" would be read as "2012".
    (r"(?<=%20)\d+(?=%20hard%20engineering%20problems)", "problems"),
    (r"(?<=%20)\d+(?=%20hard%20problems)", "problems"),
    (r"(?<=%20)\d+(?=%20tests\b)", "tests"),
    (r"(?<=%20)\d+(?=%20doctests\b)", "doctests"),
)


def refresh_counts(html: str, stats: dict) -> str:
    """Rewrite every stale count outside the JSON-LD block, idempotently."""
    for pattern, key in COUNT_PATTERNS:
        html = re.sub(pattern, str(stats[key]), html)
    return html


def render_index(current: str, data: dict) -> str:
    if MARKER_START not in current or MARKER_END not in current:
        raise SystemExit(
            "site/index.html is missing the seo:jsonld markers — restore them before generating"
        )
    head, rest = current.split(MARKER_START, 1)
    _, tail = rest.split(MARKER_END, 1)
    return (
        refresh_counts(head, data["stats"])
        + render_jsonld(data)
        + refresh_counts(tail, data["stats"])
    )


# ------------------------------------------------------------------ main -- #
def build(check: bool = False) -> int:
    if not DATA.is_file():
        raise SystemExit("site/data/problems.json is missing — run: python scripts/build_catalog.py")
    data = json.loads(DATA.read_text(encoding="utf-8"))

    current_html = INDEX.read_text(encoding="utf-8")
    outputs = {
        ROBOTS: render_robots(data),
        SITEMAP: render_sitemap(data),
        INDEX: render_index(current_html, data),
    }

    stale = 0
    for path, content in outputs.items():
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing == content:
            continue
        if check:
            stale += 1
            print(f"stale: {path.relative_to(ROOT)} — run: python scripts/build_seo.py", file=sys.stderr)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")

    if check:
        if stale:
            return 1
        print("SEO files up to date")
        return 0

    stats = data["stats"]
    links = sum(1 for _ in data["problems"])
    print(
        f"SEO: {links} deep links, {stats['problems']} problems, "
        f"{stats['categories']} categories, canonical {SITE_URL}/"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when the generated files are stale"
    )
    args = parser.parse_args(argv)
    return build(check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
